'use strict';
// Arithmetic/contract regressions run on CI. Real pixels/audio are checked in
// the browser workflow and decoded by FFmpeg, not inferred from these tests.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const scope={window:{},console};
vm.runInNewContext(fs.readFileSync('web/audio-filters.js','utf8'),scope);
vm.runInNewContext(fs.readFileSync('web/compositor.js','utf8'),scope);
const c=scope.window.VeyCutCompositor;
const close=(actual,expected)=>assert.ok(Math.abs(actual-expected)<.00001,`${actual} != ${expected}`);
const clip={kind:'video',start:10,duration:2,speed:1,volume:2,fadeIn:.5,fadeOut:.5};
close(c.audioGain(clip,10),0);close(c.audioGain(clip,10.25),1);
close(c.audioGain(clip,11),2);close(c.audioGain(clip,11.75),1);
close(c.audioGain(clip,12),0);close(c.audioGain(clip,11,{muted:true}),0);
close(c.audioGain({...clip,muted:true},11),0);
const keyed={...clip,scale:8,keys:[{property:'scale',at:0,value:1},{property:'scale',at:1,value:3,ease:[0,0,1,1]}]};
close(c.valueAt(keyed,'scale',11),2);
assert.ok(c.ease(.5,[.42,0,1,1])<.5);
assert.ok(c.ease(.5,[0,0,.58,1])>.5);
close(c.duration({in:1,out:5,speed:2}),2);
const grey=new Uint8ClampedArray([200,100,40,83]);
c.filterPixels(grey,[{id:'concat.saturation',params:{amount:-100}}],0);
assert.deepEqual([...grey],[117,117,117,83]);
const exposure=new Uint8ClampedArray([64,64,64,99]);
c.filterPixels(exposure,[{id:'concat.exposure',params:{stops:2.4}}],0);
assert.deepEqual([...exposure],[128,128,128,99]);
const contrast=new Uint8ClampedArray([80,140,220,45]);
c.filterPixels(contrast,[{id:'concat.contrast',params:{amount:-100}}],0);
assert.deepEqual([...contrast],[125,125,125,45]);
assert.throws(()=>c.validateClip({...clip,videoEffects:[{id:'unported-native-effect'}]}),/not yet rendered/);
assert.throws(()=>c.validateClip({...clip,blend:'unknown'}),/blend/);
assert.throws(()=>c.validateClip({...clip,speedCurve:[{at:0,speed:2}]}),/native treatment/);
assert.throws(()=>c.validateClip({...clip,audioStream:1}),/audio stream/);
assert.doesNotThrow(()=>c.validateClip({...clip,filters:[{id:'concat.bass',params:{gain:5}}]}));
assert.throws(()=>c.validateClip({...clip,filters:[{id:'concat.echo'}]}),/audio filter/);
assert.throws(()=>c.validateClip({...clip,kind:'text',text:{tracking:.1}}),/letter spacing/);
let depth=0;
const ctx={save(){depth++;},restore(){depth--;},setTransform(){},fillRect(){},translate(){},rotate(){},scale(){}};
assert.throws(()=>c.render(ctx,{width:100,height:100,clips:[clip],tracks:[]},11,new Map()),/No prepared visual source/);
assert.equal(depth,0,'Rejected render restores every canvas state frame');
const painted=[];
Object.assign(ctx,{measureText:()=>({width:20}),fillText:value=>painted.push(value)});
c.render(ctx,{width:100,height:100,tracks:[{id:'bottom'},{id:'top'}],clips:[
 {...clip,id:'title-top',trackId:'top',kind:'text',text:{content:'top'}},
 {...clip,id:'title-bottom',trackId:'bottom',kind:'text',text:{content:'bottom'}}
]},11,new Map());
assert.deepEqual(painted,['bottom','top'],'Native tracks composite bottom-first');
assert.equal(depth,0);
// Native display-space packages keep alpha and use the same parameter defaults.
assert.equal(c.effectCatalog.length,8);
const pixel=(id,params,rgb=[180,120,70,31],geometry)=>{const p=new Uint8ClampedArray(rgb);c.filterPixels(p,[{id,params}],0,geometry);return [...p];};
assert.deepEqual(pixel('concat.mono',{}),pixel('concat.mono',{colour:40,contrast:40,grain:0}));
const mono=pixel('concat.mono',{colour:0,contrast:0});assert.equal(mono[0],mono[1]);assert.equal(mono[1],mono[2]);assert.equal(mono[3],31);
const warm=pixel('concat.warm',{},[128,128,128,53]),cool=pixel('concat.cool',{},[128,128,128,53]);
assert.ok(warm[0]>warm[2]);assert.ok(cool[2]>cool[0]);assert.equal(warm[3],53);
assert.deepEqual(pixel('concat.vibrance',{amount:2},[100,100,100,22]),[100,100,100,22]);
assert.deepEqual(pixel('concat.vibrance',{amount:2},[255,0,0,22]),[255,0,0,22]);
assert.throws(()=>pixel('concat.mono',{grain:1}),/grain/);
assert.throws(()=>c.validateClip({...clip,videoEffects:[{id:'concat.mono',keys:{grain:[{at:1,value:2}]}}]}),/grain/);
assert.throws(()=>pixel('concat.warm',{unexpected:3}),/parameter/);
assert.throws(()=>pixel('concat.vignette',{strength:100}),/dimensions/);
const vignette=new Uint8ClampedArray(3*3*4).fill(255);c.filterPixels(vignette,[{id:'concat.vignette',params:{strength:100}}],0,{width:3,height:3});
assert.equal(vignette[16],255);assert.ok(vignette[0]<255);assert.equal(vignette[3],255);
const shaded=new Uint8ClampedArray([128,128,128,49]);c.filterPixels(shaded,[],0,{}, {scale:0,offset:1});assert.deepEqual([...shaded],[255,255,255,49]);
// A native transition only joins adjacent clips on the same visible track.
const a={...clip,id:'a',trackId:'v',start:0,timelineStart:0,duration:1,in:0,out:1,volume:1,fadeIn:0,fadeOut:0};
const b={...a,id:'b',start:1,timelineStart:1,in:.5,out:1.5,transitionIn:{id:'cross-fade',duration:.5},keys:[{property:'scale',at:0,value:2},{property:'scale',at:1,value:4}],videoEffects:[{id:'concat.exposure',keys:{stops:[{at:0,value:0},{at:1,value:1}]}}]};
const spec={width:100,height:100,fps:30,tracks:[{id:'v'}],clips:[a,b]},before=JSON.stringify(spec),joined=c.resolveTransitions(spec),incoming=joined.clips.find(x=>x.id==='b');
assert.equal(JSON.stringify(spec),before,'Rendering never mutates native project');assert.equal(c.resolveTransitions(joined),joined,'Adapter is idempotent');
close(c.start(incoming),.5);close(c.duration(incoming),1.5);close(c.sourceTime(incoming,.75),.25);close(c.opacityAt(incoming,.75),.5);close(c.audioGain(incoming,.75),.5);
close(c.valueAt(incoming,'scale',1),2+2/3);close(c.valueAt(incoming,'scale',1.5),2+4/3);
close(incoming.keys[0].at,0);close(incoming.keys[1].at,1);
close(incoming.videoEffects[0].keys.stops[0].at,0);close(incoming.videoEffects[0].keys.stops[1].at,1);
const noHandle=c.resolveTransitions({...spec,clips:[a,{...b,in:0,out:1}]}),held=noHandle.clips.find(c.isHold);
assert.ok(held);assert.notEqual(held.id,b.id);close(c.sourceTime(held,.8),0);close(c.audioGain(held,.8),0);close(c.valueAt(held,'scale',.8),2);assert.equal(JSON.stringify(held.videoEffects),JSON.stringify(b.videoEffects));
const heldEffectStart=new Uint8ClampedArray([80,80,80,29]),heldEffectEnd=new Uint8ClampedArray(heldEffectStart);
c.filterPixels(heldEffectStart,held.videoEffects,0);c.filterPixels(heldEffectEnd,held.videoEffects,1);assert.ok(heldEffectEnd[0]>heldEffectStart[0],'Native holds retain effect-key animation despite frozen decoded source');assert.equal(heldEffectEnd[3],29);
close(c.start(noHandle.clips.find(x=>x.id==='b')),1);
const image=c.resolveTransitions({...spec,clips:[a,{...b,kind:'image',in:0,out:1}]}).clips.find(x=>x.id==='b');assert.ok(!c.isHold(image));close(c.start(image),.5);
assert.equal(c.resolveTransitions({...spec,clips:[a,{...b,start:1.1,timelineStart:1.1}]}).clips.length,2);
assert.equal(c.resolveTransitions({...spec,clips:[a,{...b,in:0,out:1,transitionIn:{id:'cross-fade',duration:.01}}]}).clips.length,2);
const dip=id=>c.resolveTransitions({...spec,fps:20,clips:[a,{...b,transitionIn:{id,duration:.5}}]});
const black=dip('fade-black'),white=dip('fade-white');close(c.transitionShading(black.clips[0],.9).scale,.4);close(c.transitionShading(black.clips[1],1).scale,0);close(c.transitionShading(black.clips[1],1.25).scale,1);close(c.transitionShading(white.clips[1],1).offset,1);
assert.throws(()=>c.resolveTransitions({...spec,clips:[a,{...b,transitionIn:{id:'unported',duration:.5}}]}),/not available/);
console.log('Browser compositor arithmetic, native transition adapters and refusal regressions passed.');
